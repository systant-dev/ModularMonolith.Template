using System.Collections.Immutable;
using System.Text;

namespace ModularMonolith.Template.ModularGen.Emit;

internal static class ModuleRegistrationEmitter
{
    #region Public Method Declarations

    public static string Emit(ImmutableArray<string> moduleTypes)
    {
        StringBuilder registrations = new();

        foreach (string moduleType in moduleTypes.OrderBy(static name => name, StringComparer.Ordinal))
        {
            registrations.Append("[assembly: ModuleRegistration<");
            registrations.Append(moduleType);
            registrations.AppendLine(">]");
        }

        string source = $$"""
            // <auto-generated />
            #nullable enable

            using ModularMonolith.Template.SharedKernel.Modular;

            {{registrations.ToString().TrimEnd()}}

            """;
        return source;
    }

    #endregion
}

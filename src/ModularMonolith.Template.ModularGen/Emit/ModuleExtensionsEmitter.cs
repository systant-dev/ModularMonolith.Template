using ModularMonolith.Template.ModularGen.Models;
using ModularMonolith.Template.SourceGenerators.Shared.Collections;
using System.Text;

namespace ModularMonolith.Template.ModularGen.Emit;

internal static class ModuleExtensionsEmitter
{
    #region Field Declarations

    private const string ModulesConfigurationSection = "Modules";

    private const string ModuleEnabledConfigurationKey = "Enabled";

    private const bool ModuleEnabledByDefault = true;

    #endregion

    #region Public Method Declarations

    public static string Emit(string namespaceName, string className, string methodName, EquatableArray<ModuleInfo> modules)
    {
        string registrations = EmitRegistrations(modules);

        return $$"""
            // <auto-generated />
            #nullable enable

            using Microsoft.Extensions.Configuration;
            using Microsoft.Extensions.DependencyInjection;
            using ModularMonolith.Template.SharedKernel.Modular;

            namespace {{namespaceName}};

            [global::System.CodeDom.Compiler.GeneratedCode("ModularMonolith.Template.ModularGen", null)]
            [global::System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverage]
            public static partial class {{className}}
            {
                private static partial void {{methodName}}(IServiceCollection serviceCollection, IConfiguration configuration)
                {
            {{registrations}}
                }
            }

            """;
    }

    #endregion

    #region Private Method Declarations

    private static string EmitRegistrations(EquatableArray<ModuleInfo> modules)
    {
        StringBuilder builder = new();
        string enabledDefault = ModuleEnabledByDefault ? "true" : "false";
        int count = 0;

        foreach (ModuleInfo moduleInfo in modules.OrderBy(module => module.ModuleNamespace).ThenBy(module => module.ModuleName))
        {
            builder.Append($$"""
                        if (configuration.GetValue<bool>("{{ModulesConfigurationSection}}:{{moduleInfo.ModuleNamespace}}:{{ModuleEnabledConfigurationKey}}", {{enabledDefault}}))
                        {
                            global::{{moduleInfo.ModuleNamespace}}.{{moduleInfo.ModuleName}} module{{count}} = new();
                            module{{count}}.RegisterServices(serviceCollection);
                            ((global::ModularMonolith.Template.SharedKernel.Modular.IModule)module{{count}}).RegisterHealthChecks(serviceCollection.AddHealthChecks());
                        }

                """);

            count++;
        }

        string source = builder.ToString();
        return source;
    }

    #endregion
}

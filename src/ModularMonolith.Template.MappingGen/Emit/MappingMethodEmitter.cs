using ModularMonolith.Template.MappingGen.Models;
using System.Collections.Immutable;
using System.Text;

namespace ModularMonolith.Template.MappingGen.Emit;

internal static class MappingMethodEmitter
{
    #region Public Method Declarations

    public static string Emit(MapMethodInfo info, ImmutableArray<MapTargetInfo> targets)
    {
        StringBuilder builder = new();

        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();

        bool hasNamespace = !string.IsNullOrEmpty(info.Namespace);
        string indent = hasNamespace ? "    " : string.Empty;

        if (hasNamespace)
        {
            builder.Append("namespace ");
            builder.AppendLine(info.Namespace);
            builder.AppendLine("{");
        }

        builder.Append(indent);
        builder.Append("partial ");
        builder.Append(info.ContainingTypeKeyword);
        builder.Append(' ');
        builder.AppendLine(info.ContainingTypeName);
        builder.Append(indent);
        builder.AppendLine("{");

        builder.Append(indent);
        builder.Append("    ");
        builder.Append(info.Accessibility);
        builder.Append(" static partial ");
        builder.Append(info.TypeParameterName);
        builder.Append(' ');
        builder.Append(info.MethodName);
        builder.Append('<');
        builder.Append(info.TypeParameterName);
        builder.Append(">(this ");
        builder.Append(info.SourceTypeName);
        builder.Append(' ');
        builder.Append(info.SourceParameterName);
        builder.Append(')');
        builder.Append(info.ConstraintClause);
        builder.AppendLine();

        builder.Append(indent);
        builder.AppendLine("    {");

        foreach (MapTargetInfo target in targets.OrderBy(t => t.TargetTypeName, System.StringComparer.Ordinal))
        {
            builder.Append(indent);
            builder.Append("        if (typeof(");
            builder.Append(info.TypeParameterName);
            builder.Append(") == typeof(");
            builder.Append(target.TargetTypeName);
            builder.AppendLine("))");
            builder.Append(indent);
            builder.AppendLine("        {");

            builder.Append(indent);
            builder.Append("            return (");
            builder.Append(info.TypeParameterName);
            builder.Append(")(object)new ");
            builder.Append(target.TargetTypeName);

            if (target.Assignments.Length > 0)
            {
                builder.AppendLine();
                builder.Append(indent);
                builder.AppendLine("            {");

                foreach (MapPropertyAssignment assignment in target.Assignments)
                {
                    builder.Append(indent);
                    builder.Append("                ");
                    builder.Append(assignment.TargetProperty);
                    builder.Append(" = ");
                    builder.Append(info.SourceParameterName);
                    builder.Append('.');
                    builder.Append(assignment.SourceProperty);
                    builder.AppendLine(",");
                }

                builder.Append(indent);
                builder.AppendLine("            };");
            }
            else
            {
                builder.AppendLine("();");
            }

            builder.Append(indent);
            builder.AppendLine("        }");
        }

        builder.Append(indent);
        builder.Append("        throw new global::System.NotSupportedException($\"No mapping is generated from '");
        builder.Append(info.SourceTypeName);
        builder.Append("' to '{typeof(");
        builder.Append(info.TypeParameterName);
        builder.AppendLine(")}'.\");");

        builder.Append(indent);
        builder.AppendLine("    }");
        builder.Append(indent);
        builder.AppendLine("}");

        if (hasNamespace)
        {
            builder.AppendLine("}");
        }

        string source = builder.ToString();
        return source;
    }

    #endregion
}

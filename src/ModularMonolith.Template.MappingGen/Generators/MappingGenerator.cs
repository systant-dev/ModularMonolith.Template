using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using ModularMonolith.Template.MappingGen.Diagnostics;
using ModularMonolith.Template.MappingGen.Emit;
using ModularMonolith.Template.MappingGen.Models;
using ModularMonolith.Template.SourceGen.Common.Models;
using System.Collections.Immutable;

namespace ModularMonolith.Template.MappingGen.Generators;

[Generator]
public sealed class MappingGenerator : IIncrementalGenerator
{
    #region Field Declarations

    private const string MapAttributeName = "ModularMonolith.Template.MappingGen.MapAttribute";

    private const string MapAttributeSource = """
        // <auto-generated />
        #nullable enable
        namespace ModularMonolith.Template.MappingGen
        {
            /// <summary>
            /// Marks a static partial generic method whose body should be generated to map the
            /// public properties of the source parameter onto a new instance of the target type.
            /// </summary>
            [global::System.AttributeUsage(global::System.AttributeTargets.Method, AllowMultiple = false, Inherited = false)]
            [global::System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverage]
            internal sealed class MapAttribute : global::System.Attribute
            {
            }
        }
        """;

    private static readonly SymbolDisplayFormat FullyQualifiedFormat = SymbolDisplayFormat.FullyQualifiedFormat;

    #endregion

    #region Public Method Declarations

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(static postContext =>
            postContext.AddSource("MapAttribute.g.cs", MapAttributeSource));

        IncrementalValueProvider<ImmutableArray<MapMethodInfo>> methodProvider = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                MapAttributeName,
                predicate: static (node, _) => IsCandidateMethod(node),
                transform: static (attributeContext, _) => GetMapMethodInfo(attributeContext))
            .Where(static info => info is not null)
            .Select(static (info, _) => info!.Value)
            .Collect()
            .WithTrackingName("MapMethods");

        IncrementalValueProvider<ImmutableArray<MapTargetInfo>> targetProvider = context.SyntaxProvider
            .CreateSyntaxProvider(
                predicate: static (node, _) => IsCandidateInvocation(node),
                transform: static (syntaxContext, cancellationToken) => GetMapTargetInfo(syntaxContext, cancellationToken))
            .Where(static target => target is not null)
            .Select(static (target, _) => target!.Value)
            .Collect()
            .WithTrackingName("MapTargets");

        context.RegisterSourceOutput(methodProvider.Combine(targetProvider), static (sourceContext, pair) =>
        {
            ImmutableArray<MapMethodInfo> methods = pair.Left;
            ImmutableArray<MapTargetInfo> targets = pair.Right;

            foreach (MapMethodInfo method in methods)
            {
                ImmutableArray<MapTargetInfo> methodTargets = [.. targets
                    .Where(target => target.Key == method.Key)
                    .GroupBy(target => target.TargetTypeName)
                    .Select(group => group.First())];

                foreach (MapTargetInfo target in targets.Where(target => target.Key == method.Key))
                {
                    if (target.UnmappedRequiredMembers.Length > 0)
                    {
                        sourceContext.ReportDiagnostic(Diagnostic.Create(
                            MappingDiagnostics.MissingRequiredMember,
                            target.Location?.ToLocation(),
                            method.SourceTypeName,
                            target.TargetTypeName,
                            string.Join(", ", target.UnmappedRequiredMembers)));
                    }
                }

                string source = GenerateMapMethod(method, methodTargets);
                string hintName = $"{method.Key}.g.cs";
                sourceContext.AddSource(hintName, source);
            }
        });
    }

    #endregion

    #region Private Method Declarations

    private static bool IsCandidateMethod(SyntaxNode node)
    {
        return node is MethodDeclarationSyntax method
            && method.Modifiers.Any(SyntaxKind.PartialKeyword)
            && method.Modifiers.Any(SyntaxKind.StaticKeyword)
            && method.TypeParameterList is not null
            && method.TypeParameterList.Parameters.Count == 1
            && method.ParameterList.Parameters.Count >= 1
            && method.Parent is TypeDeclarationSyntax;
    }

    private static MapMethodInfo? GetMapMethodInfo(GeneratorAttributeSyntaxContext context)
    {
        if (context.TargetSymbol is not IMethodSymbol methodSymbol)
        {
            return null;
        }

        if (!methodSymbol.IsStatic
            || !methodSymbol.IsPartialDefinition
            || methodSymbol.TypeParameters.Length != 1
            || methodSymbol.Parameters.Length < 1)
        {
            return null;
        }

        ITypeParameterSymbol typeParameter = methodSymbol.TypeParameters[0];
        if (!SymbolEqualityComparer.Default.Equals(methodSymbol.ReturnType, typeParameter))
        {
            return null;
        }

        if (methodSymbol.Parameters[0].Type is not INamedTypeSymbol sourceType)
        {
            return null;
        }

        INamedTypeSymbol containingType = methodSymbol.ContainingType;

        return new MapMethodInfo(
            Key: CreateKey(containingType, methodSymbol.Name),
            Namespace: containingType.ContainingNamespace.IsGlobalNamespace
                ? string.Empty
                : containingType.ContainingNamespace.ToDisplayString(),
            ContainingTypeName: containingType.Name,
            ContainingTypeKeyword: GetTypeKeyword(containingType),
            Accessibility: GetAccessibilityKeyword(methodSymbol.DeclaredAccessibility),
            MethodName: methodSymbol.Name,
            TypeParameterName: typeParameter.Name,
            ConstraintClause: GetConstraintClause(typeParameter),
            SourceParameterName: methodSymbol.Parameters[0].Name,
            SourceTypeName: sourceType.ToDisplayString(FullyQualifiedFormat));
    }

    private static bool IsCandidateInvocation(SyntaxNode node)
    {
        return node is InvocationExpressionSyntax invocation
            && TryGetGenericName(invocation) is { } genericName
            && genericName.TypeArgumentList.Arguments.Count == 1;
    }

    private static GenericNameSyntax? TryGetGenericName(InvocationExpressionSyntax invocation)
    {
        return invocation.Expression switch
        {
            MemberAccessExpressionSyntax { Name: GenericNameSyntax generic } => generic,
            GenericNameSyntax generic => generic,
            _ => null,
        };
    }

    private static MapTargetInfo? GetMapTargetInfo(GeneratorSyntaxContext context, CancellationToken cancellationToken)
    {
        if (context.Node is not InvocationExpressionSyntax invocation)
        {
            return null;
        }

        if (context.SemanticModel.GetSymbolInfo(invocation, cancellationToken).Symbol is not IMethodSymbol methodSymbol)
        {
            return null;
        }

        IMethodSymbol definition = methodSymbol.ReducedFrom ?? methodSymbol.OriginalDefinition;
        if (!HasMapAttribute(definition))
        {
            return null;
        }

        if (methodSymbol.TypeArguments.Length != 1
            || methodSymbol.TypeArguments[0] is not INamedTypeSymbol targetType
            || targetType.TypeKind == TypeKind.TypeParameter
            || targetType.TypeKind == TypeKind.Error)
        {
            return null;
        }

        if (definition.Parameters.Length < 1 || definition.Parameters[0].Type is not INamedTypeSymbol sourceType)
        {
            return null;
        }

        ImmutableArray<MapPropertyAssignment> assignments = ComputeAssignments(sourceType, targetType, context.SemanticModel.Compilation, out ImmutableArray<string> unmappedRequiredMembers);

        return new MapTargetInfo(
            Key: CreateKey(definition.ContainingType, definition.Name),
            TargetTypeName: targetType.ToDisplayString(FullyQualifiedFormat),
            Assignments: assignments,
            UnmappedRequiredMembers: unmappedRequiredMembers,
            Location: LocationInfo.CreateFrom(invocation));
    }

    private static bool HasMapAttribute(IMethodSymbol methodSymbol)
    {
        foreach (AttributeData attribute in methodSymbol.GetAttributes())
        {
            if (attribute.AttributeClass?.ToDisplayString() == MapAttributeName)
            {
                return true;
            }
        }

        return false;
    }

    private static ImmutableArray<MapPropertyAssignment> ComputeAssignments(INamedTypeSymbol sourceType, INamedTypeSymbol targetType, Compilation compilation, out ImmutableArray<string> unmappedRequiredMembers)
    {
        Dictionary<string, IPropertySymbol> sourceProperties = GetReadableProperties(sourceType);
        ImmutableArray<MapPropertyAssignment>.Builder builder = ImmutableArray.CreateBuilder<MapPropertyAssignment>();
        ImmutableArray<string>.Builder unmappedRequired = ImmutableArray.CreateBuilder<string>();

        foreach (IPropertySymbol targetProperty in GetWritableProperties(targetType))
        {
            bool mapped = false;

            if (sourceProperties.TryGetValue(targetProperty.Name.ToLowerInvariant(), out IPropertySymbol sourceProperty))
            {
                Conversion conversion = compilation.ClassifyConversion(sourceProperty.Type, targetProperty.Type);
                if (conversion.IsIdentity || conversion.IsImplicit)
                {
                    builder.Add(new MapPropertyAssignment(targetProperty.Name, sourceProperty.Name));
                    mapped = true;
                }
            }

            if (!mapped && targetProperty.IsRequired)
            {
                unmappedRequired.Add(targetProperty.Name);
            }
        }

        unmappedRequiredMembers = unmappedRequired.ToImmutable();
        return builder.ToImmutable();
    }

    private static Dictionary<string, IPropertySymbol> GetReadableProperties(INamedTypeSymbol type)
    {
        Dictionary<string, IPropertySymbol> properties = new(System.StringComparer.Ordinal);

        for (INamedTypeSymbol? current = type; current is not null && current.SpecialType != SpecialType.System_Object; current = current.BaseType)
        {
            foreach (ISymbol member in current.GetMembers())
            {
                if (member is not IPropertySymbol property
                    || property.DeclaredAccessibility != Accessibility.Public
                    || property.IsStatic
                    || property.IsIndexer
                    || property.GetMethod is null
                    || property.GetMethod.DeclaredAccessibility != Accessibility.Public)
                {
                    continue;
                }

                string key = property.Name.ToLowerInvariant();
                if (!properties.ContainsKey(key))
                {
                    properties.Add(key, property);
                }
            }
        }

        return properties;
    }

    private static IEnumerable<IPropertySymbol> GetWritableProperties(INamedTypeSymbol type)
    {
        HashSet<string> seen = new(System.StringComparer.Ordinal);

        for (INamedTypeSymbol? current = type; current is not null && current.SpecialType != SpecialType.System_Object; current = current.BaseType)
        {
            foreach (ISymbol member in current.GetMembers())
            {
                if (member is not IPropertySymbol property
                    || property.DeclaredAccessibility != Accessibility.Public
                    || property.IsStatic
                    || property.IsIndexer
                    || property.SetMethod is null
                    || property.SetMethod.DeclaredAccessibility != Accessibility.Public)
                {
                    continue;
                }

                if (seen.Add(property.Name))
                {
                    yield return property;
                }
            }
        }
    }

    private static string CreateKey(INamedTypeSymbol containingType, string methodName)
    {
        return $"{containingType.ToDisplayString()}.{methodName}";
    }

    private static string GetTypeKeyword(INamedTypeSymbol type)
    {
        if (type.IsRecord)
        {
            return type.TypeKind == TypeKind.Struct ? "record struct" : "record";
        }

        return type.TypeKind == TypeKind.Struct ? "struct" : "class";
    }

    private static string GetConstraintClause(ITypeParameterSymbol typeParameter)
    {
        List<string> constraints = [];

        if (typeParameter.HasReferenceTypeConstraint)
        {
            constraints.Add("class");
        }
        else if (typeParameter.HasUnmanagedTypeConstraint)
        {
            constraints.Add("unmanaged");
        }
        else if (typeParameter.HasValueTypeConstraint)
        {
            constraints.Add("struct");
        }
        else if (typeParameter.HasNotNullConstraint)
        {
            constraints.Add("notnull");
        }

        foreach (ITypeSymbol constraintType in typeParameter.ConstraintTypes)
        {
            constraints.Add(constraintType.ToDisplayString(FullyQualifiedFormat));
        }

        if (typeParameter.HasConstructorConstraint)
        {
            constraints.Add("new()");
        }

        if (constraints.Count == 0)
        {
            return string.Empty;
        }

        return $" where {typeParameter.Name} : {string.Join(", ", constraints)}";
    }

    private static string GetAccessibilityKeyword(Accessibility accessibility)
    {
        return accessibility switch
        {
            Accessibility.Public => "public",
            Accessibility.Internal => "internal",
            Accessibility.Protected => "protected",
            Accessibility.ProtectedOrInternal => "protected internal",
            Accessibility.ProtectedAndInternal => "private protected",
            Accessibility.Private => "private",
            _ => "internal",
        };
    }

    private static string GenerateMapMethod(MapMethodInfo info, ImmutableArray<MapTargetInfo> targets)
    {
        return MappingMethodEmitter.Emit(info, targets);
    }

    #endregion
}
using Microsoft.CodeAnalysis;
using ModularMonolith.Template.SourceGen.Analysis;
using System.Collections.Immutable;
using System.Text;

namespace ModularMonolith.Template.SourceGen.Generators;

[Generator]
public sealed class ModuleRegistrationGenerator : IIncrementalGenerator
{
    #region Field Declarations

    private const string ModuleAttributeName = "ModularMonolith.Template.SharedKernel.Modular.ModuleAttribute";
    private const string ModuleInterfaceName = "ModularMonolith.Template.SharedKernel.Modular.IModule";

    #endregion

    #region Public Method Declarations

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValueProvider<ImmutableArray<string>> moduleTypesProvider = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                ModuleAttributeName,
                predicate: static (_, _) => true,
                transform: static (attributeContext, _) => GetModuleTypeName(attributeContext))
            .Where(static typeName => typeName is not null)
            .Select(static (typeName, _) => typeName!)
            .Collect()
            .WithTrackingName("ModuleRegistrations");

        context.RegisterSourceOutput(moduleTypesProvider, static (sourceContext, moduleTypes) =>
        {
            if (moduleTypes.IsDefaultOrEmpty)
            {
                return;
            }

            string source = GenerateAssemblyAttributes(moduleTypes);
            sourceContext.AddSource("ModuleRegistrations.g.cs", source);
        });
    }

    #endregion

    #region Private Method Declarations

    private static string? GetModuleTypeName(GeneratorAttributeSyntaxContext context)
    {
        if (context.TargetSymbol is not INamedTypeSymbol type)
        {
            return null;
        }

        INamedTypeSymbol? moduleInterface = context.SemanticModel.Compilation.GetTypeByMetadataName(ModuleInterfaceName);
        if (moduleInterface is null || !ModuleSymbolAnalyser.IsInstantiableModule(type, moduleInterface))
        {
            return null;
        }

        return type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
    }

    private static string GenerateAssemblyAttributes(ImmutableArray<string> moduleTypes)
    {
        StringBuilder builder = new();

        builder.AppendLine("// <auto-generated />");
        builder.AppendLine();
        builder.AppendLine("using ModularMonolith.Template.SharedKernel.Modular;");
        builder.AppendLine();

        foreach (string moduleType in moduleTypes.OrderBy(static name => name, StringComparer.Ordinal))
        {
            builder.Append("[assembly: ModuleRegistration<");
            builder.Append(moduleType);
            builder.AppendLine(">]");
        }

        return builder.ToString();
    }

    #endregion
}

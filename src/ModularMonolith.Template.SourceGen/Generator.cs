using Microsoft.CodeAnalysis;
using System.Collections.Immutable;
using System.Text;

namespace ModularMonolith.Template.SourceGen;

[Generator]
public sealed class ModuleGenerator : IIncrementalGenerator
{
    #region Field Declarations

    private const string ModuleAttributeName = "ModularMonolith.Template.SharedKernel.Modular.ModuleAttribute";

    #endregion

    #region Public Method Declarations

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValueProvider<ImmutableArray<ModuleInfo>> modulesProvider = context.CompilationProvider.Select(static (compilation, _) => GetModules(compilation)).WithTrackingName("GetModules");
        context.RegisterSourceOutput(modulesProvider, static (context, modules) =>
                                                        {
                                                            string source = GenerateModuleExtensions(modules);
                                                            context.AddSource("ModuleServiceCollectionExtensions.g.cs", source);
                                                        });
    }

    #endregion

    #region Private Method Declarations

    private static ImmutableArray<ModuleInfo> GetModules(Compilation compilation)
    {
        ImmutableArray<ModuleInfo>.Builder builder = ImmutableArray.CreateBuilder<ModuleInfo>();
        CollectModules(compilation.Assembly.GlobalNamespace, builder);

        foreach (IAssemblySymbol reference in compilation.SourceModule.ReferencedAssemblySymbols)
        {
            CollectModules(reference.GlobalNamespace, builder);
        }

        return builder.ToImmutable();
    }

    private static void CollectModules(INamespaceSymbol namespaceSymbol, ImmutableArray<ModuleInfo>.Builder modules)
    {
        foreach (INamedTypeSymbol type in namespaceSymbol.GetTypeMembers())
        {
            CollectModuleType(type, modules);
        }
        foreach (INamespaceSymbol childNamespace in namespaceSymbol.GetNamespaceMembers())
        {
            CollectModules(childNamespace, modules);
        }
    }

    private static void CollectModuleType(INamedTypeSymbol type, ImmutableArray<ModuleInfo>.Builder modules)
    {
        if (HasModuleAttribute(type))
        {
            string moduleName = type.Name;
            string moduleNamespace = type.ContainingNamespace.ToDisplayString();
            ModuleInfo module = new(moduleName, moduleNamespace);
            modules.Add(module);
        }
        foreach (INamedTypeSymbol nestedType in type.GetTypeMembers())
        {
            CollectModuleType(nestedType, modules);
        }
    }

    private static bool HasModuleAttribute(INamedTypeSymbol type)
    {
        return type.GetAttributes().Any(attribute => attribute.AttributeClass?.ToDisplayString() == ModuleAttributeName);
    }

    private static string GenerateModuleExtensions(ImmutableArray<ModuleInfo> modules)
    {
        StringBuilder builder = new();

        builder.AppendLine("// <auto-generated />");
        builder.AppendLine();
        builder.AppendLine("using Microsoft.Extensions.DependencyInjection;");
        builder.AppendLine("using ModularMonolith.Template.SharedKernel.Modular;");
        builder.AppendLine();
        builder.AppendLine("namespace ModularMonolith.Template.Api.Modular;");
        builder.AppendLine();
        builder.AppendLine("public static partial class ModuleServiceCollectionExtensions");
        builder.AppendLine("{");
        builder.AppendLine("    private static partial void GetModules(IServiceCollection serviceCollection)");
        builder.AppendLine("    {");

        int count = 0;
        foreach (ModuleInfo moduleInfo in modules.OrderBy(module => module.ModuleNamespace).ThenBy(module => module.ModuleName))
        {
            builder.Append("        ");
            builder.Append(moduleInfo.ModuleNamespace);
            builder.Append('.');
            builder.Append(moduleInfo.ModuleName);
            builder.AppendLine($" module{count} = new();");
            builder.AppendLine($"        module{count++}.RegisterServices(serviceCollection);");
            builder.AppendLine();
        }

        builder.AppendLine("    }");
        builder.AppendLine("}");

        return builder.ToString();
    }

    #endregion
}
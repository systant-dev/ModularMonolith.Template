using ModularMonolith.Template.ComplianceGen.Models;
using System.Collections.Generic;
using System.Text;

namespace ModularMonolith.Template.ComplianceGen.Emit;

internal static class RedactorEmitter
{
    #region Public Method Declarations

    public static string Emit(ClassificationProfileInfo profile)
    {
        StringBuilder builder = new();

        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();

        bool hasNamespace = !string.IsNullOrEmpty(profile.Namespace);
        string indent = hasNamespace ? "    " : string.Empty;

        if (hasNamespace)
        {
            builder.Append("namespace ");
            builder.AppendLine(profile.Namespace);
            builder.AppendLine("{");
        }

        builder.Append(indent);
        builder.Append(profile.Accessibility);
        builder.Append(" partial ");
        builder.Append(profile.ProfileTypeKeyword);
        builder.Append(' ');
        builder.Append(profile.ProfileTypeName);
        builder.Append(" : global::ModularMonolith.Template.SharedKernel.Compliance.Redaction.IModelRedactor<");
        builder.Append(profile.ModelTypeName);
        builder.AppendLine(">");
        builder.Append(indent);
        builder.AppendLine("{");

        builder.Append(indent);
        builder.Append("    public ");
        builder.Append(profile.ModelTypeName);
        builder.Append(" Redact(");
        builder.Append(profile.ModelTypeName);
        builder.AppendLine(" model, global::ModularMonolith.Template.SharedKernel.Compliance.Redaction.IRedactorProvider redactorProvider)");
        builder.Append(indent);
        builder.AppendLine("    {");

        foreach (ClassifiedMemberInfo member in profile.Members)
        {
            if (!member.IsSupportedSelector || !member.IsString)
            {
                continue;
            }

            EmitMemberAssignment(builder, indent, member);
        }

        builder.Append(indent);
        builder.AppendLine("        return model;");
        builder.Append(indent);
        builder.AppendLine("    }");
        builder.Append(indent);
        builder.AppendLine("}");

        if (hasNamespace)
        {
            builder.AppendLine("}");
        }

        return builder.ToString();
    }

    #endregion

    #region Private Method Declarations

    private static void EmitMemberAssignment(StringBuilder builder, string indent, ClassifiedMemberInfo member)
    {
        string[] segments = member.MemberPath.Split('.');
        bool isNested = segments.Length > 1;
        string bodyIndent = isNested ? indent + "            " : indent + "        ";

        if (isNested)
        {
            string guard = string.Join(" && ", BuildNullGuards(segments));
            builder.Append(indent);
            builder.Append("        if (");
            builder.Append(guard);
            builder.AppendLine(")");
            builder.Append(indent);
            builder.AppendLine("        {");
        }

        builder.Append(bodyIndent);
        builder.Append("model.");
        builder.Append(member.MemberPath);
        builder.Append(" = redactorProvider.GetRedactor(");
        builder.Append(member.ClassificationName);
        builder.Append(").Redact(model.");
        builder.Append(member.MemberPath);
        builder.AppendLine(");");

        if (isNested)
        {
            builder.Append(indent);
            builder.AppendLine("        }");
        }
    }

    private static IEnumerable<string> BuildNullGuards(string[] segments)
    {
        string prefix = "model";
        for (int index = 0; index < segments.Length - 1; index++)
        {
            prefix += "." + segments[index];
            yield return prefix + " is not null";
        }
    }

    #endregion
}
